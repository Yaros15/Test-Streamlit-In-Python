
import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

st.title("Самый большой заголовок")          # Уровень 1 (как H1 в HTML)
st.header("Раздел первого уровня")           # Уровень 2 (H2)
st.subheader("Подраздел")                    # Уровень 3 (H3)
st.caption("Это мелкий текст-подпись")       # Не заголовок, но пригодится

# --- 1. Строки и числа ---
st.write("Привет, это мое первое приложение!")
st.write("Мне 25 лет, а число Пи примерно:", 3.14159)

# --- 2. Переменные и формулы ---
x = 10
y = 20
st.write("Сумма x и y равна:", x + y)

# --- 3. Списки и словари (Python-объекты) ---
my_list = [1, 2, 3, 4, 5]
st.write("Мой список:", my_list)

# --- 4. Таблица из Pandas (самое вкусное!) ---
my_dict = {"имя": "Анна", "город": "Москва"}
st.write("Мой словарь:", my_dict)

df = pd.DataFrame(
    {
        "Студент": ["Аня", "Петя", "Маша"],
        "Оценка": [5, 4, 5],
        "Возраст": [20, 21, 19]
    }
)

st.write("Таблица успеваемости:", df)

# --- 5. График (он сам подхватит матплотлиб!) ---
fig, ax = plt.subplots()
ax.plot([1, 2, 3, 4], [10, 20, 25, 30], marker='o')
ax.set_title("Мой первый график")
st.write(fig) 
